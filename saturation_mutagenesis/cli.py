"""Command-line interface for the standalone saturation mutagenesis workflow."""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

from attack_geometry.boltz import BoltzConfig
from attack_geometry.config import GeometryConfig, LigandSpec, PartnerChainSpec, load_config
from attack_geometry.mechanisms import get_mechanism, merge_mechanism_thresholds
from attack_geometry.structure import load_structure

from .pipeline import (
    SaturationConfig,
    evaluate_saturation_campaign,
    prepare_boltz_inputs,
    run_boltz_campaign,
    run_saturation_pipeline,
)
from .pocket import define_pocket
from .variants import (
    AA20,
    build_multisite_variants,
    build_variants,
    read_variants_tsv,
    write_variants_fasta,
    write_variants_tsv,
)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="saturation-mutagenesis",
        description=(
            "Saturation mutagenesis workflow: pocket scanning, single/multi-site "
            "variant library generation, Boltz-2 co-folding, and attack-geometry ranking."
        ),
    )
    sub = parser.add_subparsers(dest="command", required=True)

    # 1. scan-pocket
    p_pocket = sub.add_parser("scan-pocket", help="Identify catalytic pocket positions around the bound complex.")
    p_pocket.add_argument("--structure", type=Path, required=True, help="Holo PDB or mmCIF structure.")
    p_pocket.add_argument("--cutoff", type=float, default=5.0, help="Residue-to-complex cutoff in Å (default: 5.0).")
    p_pocket.add_argument("--link-cutoff", type=float, default=5.0, help="Component connectivity cutoff in Å.")
    p_pocket.add_argument("--components", default="", help="Comma-separated component/chain IDs (empty = all HETATM).")
    p_pocket.add_argument("--anchor", default="", help="Anchor component ID (empty = largest component).")
    p_pocket.add_argument("--protein-chain", default="", help="Protein chain ID (empty = all protein chains).")
    p_pocket.add_argument("--output", type=Path, default=None, help="Optional TSV output path.")

    # 2. generate-variants
    p_var = sub.add_parser("generate-variants", help="Generate single- or multi-site variant sequences.")
    p_var.add_argument("--structure", type=Path, required=True, help="Scaffold PDB or mmCIF structure.")
    p_var.add_argument("--positions", default="", help="Comma-separated 1-based residue numbers or pocket TSV path.")
    p_var.add_argument("--explicit-mutations", default="", help="Comma-separated mutations (e.g. 'S190T,D143E+S190T').")
    p_var.add_argument("--max-mutations", type=int, default=1, help="Maximum simultaneous mutations (default: 1).")
    p_var.add_argument("--alphabet", default=AA20, help="Amino acid alphabet (default: all 20 standard AAs).")
    p_var.add_argument("--label", default="enzyme", help="Variant ID prefix.")
    p_var.add_argument("--protein-chain", default="A", help="Protein chain ID (default: A).")
    p_var.add_argument("--no-wt", action="store_true", help="Omit wild-type control variant.")
    p_var.add_argument("--output-dir", type=Path, required=True, help="Directory for variants.tsv and variants.fasta.")

    # 3. prepare-boltz
    p_prep = sub.add_parser("prepare-boltz", help="Prepare Boltz-2 YAML co-folding inputs for a variant library.")
    p_prep.add_argument("--variants", type=Path, required=True, help="variants.tsv generated by generate-variants.")
    p_prep.add_argument("--config", type=Path, required=True, help="YAML/JSON config containing 'ligands'.")
    p_prep.add_argument("--protein-chain", default="A", help="Protein chain ID (default: A).")
    p_prep.add_argument("--msa-dir", type=Path, default=None, help="Optional directory of per-variant <id>.csv MSAs.")
    p_prep.add_argument("--msa-index", type=Path, default=None, help="Optional index.tsv from `boltz-cofold prepare-msa`.")
    p_prep.add_argument("--output-dir", type=Path, required=True, help="Output directory for boltz_inputs/.")

    # 4. run-boltz
    p_boltz = sub.add_parser("run-boltz", help="Run Boltz-2 co-folding on prepared YAML inputs.")
    p_boltz.add_argument("--inputs-dir", type=Path, required=True, help="Directory containing <variant_id>.yaml files.")
    p_boltz.add_argument("--results-dir", type=Path, required=True, help="Directory for Boltz-2 prediction outputs.")
    p_boltz.add_argument("--config", type=Path, default=None, help="Optional YAML/JSON config with a 'boltz' section.")
    p_boltz.add_argument("--diffusion-samples", type=int, default=None, help="Override diffusion sample count.")
    p_boltz.add_argument("--dry-run", action="store_true", help="Print commands without executing Boltz-2.")

    # 5. evaluate
    p_eval = sub.add_parser("evaluate", help="Score Boltz-2 predictions by attack geometry and confidence.")
    p_eval.add_argument("--variants", type=Path, required=True, help="variants.tsv file.")
    p_eval.add_argument("--results-dir", type=Path, required=True, help="Directory containing Boltz-2 outputs.")
    p_eval.add_argument("--config", type=Path, required=True, help="YAML/JSON config with 'geometry' and optional 'thresholds'.")
    p_eval.add_argument("--output-dir", type=Path, required=True, help="Directory for CSV/JSON summary outputs.")
    p_eval.add_argument("--protein-chain", default="A", help="Protein chain ID (default: A).")
    p_eval.add_argument("--top-k", type=int, default=20, help="Number of top ranked hits in top_hits.json.")
    p_eval.add_argument("--max-distance", type=float, default=None, help="Override max attack distance threshold (Å).")
    p_eval.add_argument("--min-angle", type=float, default=None, help="Override min attack angle threshold (deg).")

    # 6. run (end-to-end)
    p_run = sub.add_parser("run", help="Run end-to-end saturation mutagenesis from a YAML/JSON config.")
    p_run.add_argument("--config", type=Path, required=True, help="Full saturation mutagenesis YAML/JSON config.")
    p_run.add_argument("--skip-boltz", action="store_true", help="Skip running Boltz-2 (use existing outputs if present).")
    p_run.add_argument("--dry-run", action="store_true", help="Prepare inputs and print Boltz-2 commands without running.")

    return parser


def _parse_positions_arg(spec: str, seq: str) -> list[tuple[int, str]]:
    p = Path(spec).expanduser()
    nums: list[int] = []
    if p.is_file():
        with p.open(newline="") as fh:
            for row in csv.DictReader(fh, delimiter="\t"):
                if row.get("resnum"):
                    nums.append(int(row["resnum"]))
    else:
        nums = [int(x.strip()) for x in spec.split(",") if x.strip()]
    return [(n, seq[n - 1]) for n in sorted(set(nums))]


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if args.command == "scan-pocket":
        st = load_structure(args.structure)
        comps = [c.strip() for c in args.components.split(",") if c.strip()] or None
        pocket = define_pocket(
            st,
            cutoff=args.cutoff,
            components=comps,
            anchor=args.anchor or None,
            link_cutoff=args.link_cutoff,
            protein_chain=args.protein_chain or None,
        )
        rows = pocket.to_rows()
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            fields = list(rows[0]) if rows else ["chain", "resnum"]
            with args.output.open("w", newline="") as fh:
                w = csv.DictWriter(fh, fieldnames=fields, delimiter="\t")
                w.writeheader()
                w.writerows(rows)
        payload = {
            "anchor": pocket.anchor,
            "admitted_components": list(pocket.admitted),
            "excluded_components": [e.__dict__ for e in pocket.excluded],
            "n_positions": len(rows),
            "positions": rows,
        }
        sys.stdout.write(json.dumps(payload, indent=2) + "\n")
        return 0

    if args.command == "generate-variants":
        st = load_structure(args.structure)
        seq = st.sequence(args.protein_chain)
        explicit = [x.strip() for x in args.explicit_mutations.split(",") if x.strip()] or None
        if explicit is not None or args.max_mutations > 1:
            pos_pairs = _parse_positions_arg(args.positions, seq) if explicit is None else None
            variants = build_multisite_variants(
                seq,
                pos_pairs,
                label=args.label,
                alphabet=args.alphabet,
                max_mutations=args.max_mutations,
                explicit_mutations=explicit,
                include_wt=not args.no_wt,
            )
        else:
            pos_pairs = _parse_positions_arg(args.positions, seq)
            variants = build_variants(
                seq,
                pos_pairs,
                label=args.label,
                alphabet=args.alphabet,
                include_wt=not args.no_wt,
            )
        tsv = write_variants_tsv(variants, args.output_dir / "variants.tsv")
        fasta = write_variants_fasta(variants, args.output_dir / "variants.fasta")
        sys.stdout.write(
            json.dumps(
                {"n_variants": len(variants), "variants_tsv": str(tsv), "variants_fasta": str(fasta)},
                indent=2,
            )
            + "\n"
        )
        return 0

    if args.command == "prepare-boltz":
        variants = read_variants_tsv(args.variants)
        raw = load_config(args.config)
        ligands = [LigandSpec.from_dict(x) for x in raw.get("ligands", ())]
        partners = [PartnerChainSpec.from_dict(x) for x in raw.get("partner_chains", ())]
        written = prepare_boltz_inputs(
            variants,
            ligands,
            args.output_dir,
            protein_chain=args.protein_chain,
            msa_dir=args.msa_dir,
            msa_index_tsv=args.msa_index,
            partner_chains=partners,
        )
        sys.stdout.write(json.dumps({"n_inputs": len(written), "inputs_dir": str(args.output_dir / "boltz_inputs")}, indent=2) + "\n")
        return 0

    if args.command == "run-boltz":
        raw = load_config(args.config) if args.config else {}
        b_dict = dict(raw.get("boltz", {}))
        if args.diffusion_samples is not None:
            b_dict["diffusion_samples"] = args.diffusion_samples
        b_cfg = BoltzConfig.from_dict(b_dict)
        yamls = {p.stem: p for p in sorted(args.inputs_dir.glob("*.yaml"))}
        runs = run_boltz_campaign(yamls, args.results_dir, b_cfg, dry_run=args.dry_run)
        sys.stdout.write(json.dumps({"n_jobs": len(runs), "runs": runs}, indent=2) + "\n")
        return 0

    if args.command == "evaluate":
        variants = read_variants_tsv(args.variants)
        raw = load_config(args.config)
        mech = get_mechanism(raw.get("mechanism"))
        geom_cfg = GeometryConfig.from_dict(raw["geometry"])
        thresh_dict = dict(raw.get("thresholds") or {})
        if args.max_distance is not None:
            thresh_dict["max_distance_A"] = args.max_distance
        if args.min_angle is not None:
            thresh_dict["min_angle_deg"] = args.min_angle
        thresh_cfg = merge_mechanism_thresholds(mech, thresh_dict)
        cp_raw = raw.get("chain_pairs") or {}
        chain_pairs = {str(k): (str(v[0]), str(v[1])) for k, v in cp_raw.items()}
        report = evaluate_saturation_campaign(
            variants=variants,
            results_dir=args.results_dir,
            geometry_config=geom_cfg,
            output_dir=args.output_dir,
            protein_chain=args.protein_chain,
            mechanism=mech.name,
            target_angle_deg=raw.get("target_angle_deg"),
            rank_by=raw.get("rank_by"),
            thresholds=thresh_cfg,
            chain_pairs=chain_pairs,
            top_k=args.top_k,
        )
        sys.stdout.write(json.dumps(report, indent=2) + "\n")
        return 0

    if args.command == "run":
        cfg = SaturationConfig.from_file(args.config)
        result = run_saturation_pipeline(cfg, run_boltz=not args.skip_boltz, dry_run=args.dry_run)
        sys.stdout.write(json.dumps(result, indent=2) + "\n")
        return 0

    return 1


if __name__ == "__main__":
    raise SystemExit(main())
